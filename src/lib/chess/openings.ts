const BOOK = RAW.map(([eco, name, seq]) => ({ eco, name, moves: seq.split(" ") }));

export interface OpeningMatch {
  eco: string;
  name: string;
  plies: number; // number of game plies covered by the book line
}

export function identifyOpening(sans: string[]): OpeningMatch | null {
  let best: OpeningMatch | null = null;
  for (const o of BOOK) {
    if (o.moves.length > sans.length) continue;
    if (o.moves.every((m, i) => m === sans[i]) && (!best || o.moves.length > best.plies)) {
      best = { eco: o.eco, name: o.name, plies: o.moves.length };
    }
  }
  return best;
}
